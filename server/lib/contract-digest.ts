import { LINK_KINDS, PREFIX_BY_TYPE, RECORD_TYPES } from './types';

/**
 * Факты контракта человеческим языком, прямо в запрос на починку.
 *
 * Проект может держать у себя копию документации DocDD — снимок правил на
 * момент, когда её туда положили. Копия стареет, а работающая схема — эта,
 * встроенная в приложение, — меняется дальше. Модель, читающая файлы проекта,
 * не может отличить актуальный контракт от чужого снимка; она добросовестно
 * поверит тому, что нашла, и откажется чинить то, что на самом деле чинится.
 *
 * Поэтому факты не ищутся моделью — они подставляются приложением из того же
 * места, что и сама проверка, и разойтись с ней не могут.
 */

const NEW_LINE = String.fromCharCode(10);

export function contractDigest(): string {
  const lines: string[] = [
    '### Факты контракта',
    '',
    'Ниже — то, что проверяет **эта** сборка приложения, не то, что могло найтись',
    'файлом в проекте. Если в проекте лежит своя копия документации DocDD —',
    'дублирующая, вендоренная или просто старая, — она могла отстать от этой',
    'сборки. Верь этому списку, а не найденным файлам.',
    '',
    '**Типы записей и префиксы:**',
    ''
  ];

  for (const type of RECORD_TYPES) {
    lines.push(`- \`${type}\` — префикс \`${PREFIX_BY_TYPE[type]}-\`, номер: \`${PREFIX_BY_TYPE[type]}-0001\``);
  }

  lines.push(
    '',
    '**Связи** (`links`): ' + LINK_KINDS.map((kind) => `\`${kind}\``).join(', ') + '.',
    '',
    '**`superseded` — тупик.** Из него нет перехода ни в один статус, даже назад',
    'в `draft`: это осознанное правило, а не пробел. Записи, которую пометили',
    '`superseded` без реальной замены, не возвращают статус — ей находят',
    'преемника: у **уже существующей** записи (черновика или подтверждённой)',
    'дописывают `supersedes: [ID]`. Правилу важно, что связь есть, а не что',
    'преемник подтверждён — сверься с этим при плане, не изобретай статус назад.'
  );

  return lines.join(NEW_LINE);
}
